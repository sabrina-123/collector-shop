function getUserPhoto(category, itemIndex) {
  const slug = categorySlugs[category];
  const files = userPhotoFiles[category];

  if (!files) {
    return null;
  }

  const filename = files[itemIndex % files.length];
  return `/catalog-images/${slug}/${encodeURIComponent(filename)}`;
}

function buildCollection() {
  return collectionBlueprints.flatMap((blueprint, categoryIndex) => {
    const existing = curatedCollection.filter((item) => item.category_name === blueprint.category);
    const generated = Array.from({ length: itemsPerCategory - existing.length }, (_, index) => {
      const itemNumber = index + existing.length + 1;
      const price = blueprint.prices[(index + categoryIndex) % blueprint.prices.length] + ((index * 7) % 20);

      return {
        id: `${blueprint.category.toLowerCase().replaceAll(" ", "-")}-${itemNumber}`,
        title: `${blueprint.prefix} n°${itemNumber}`,
        category_name: blueprint.category,
        description: `Une belle trouvaille selectionnee pour les amateurs de ${blueprint.category.toLowerCase()}, avec une histoire et une patine uniques.`,
        price: price.toFixed(2),
        seller_username: blueprint.sellers[index % blueprint.sellers.length],
        image: blueprint.images[index % blueprint.images.length],
        is_available: true,
        is_demo: true,
      };
    });

    return [...existing, ...generated].map((item, itemIndex) => ({
      ...item,
      image: getUserPhoto(blueprint.category, itemIndex) || categoryArtwork[blueprint.category],
      fallbackImage: categoryArtwork[blueprint.category],
    }));
  });
}

export const featuredCollection = buildCollection();

export function findCollectionItem(id) {
  return featuredCollection.find((item) => item.id === id);
}
